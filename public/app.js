function pagination(result) {
  if (result.pages <= 1) return '';
  const { page, pages } = result;
  const nums = [];
  for (let i = 1; i <= pages; i++) {
    if (i === 1 || i === pages || Math.abs(i - page) <= 1) nums.push(i);
    else if (nums[nums.length - 1] !== '…') nums.push('…');
  }
  return `<nav class="pagination" aria-label="Pages">
    <button class="btn btn-secondary" data-page="${page - 1}" ${page === 1 ? 'disabled' : ''} aria-label="Previous page">←</button>
    ${nums.map((n) => (n === '…' ? '<span class="muted" style="align-self:center">…</span>' : `<button class="btn btn-secondary ${n === page ? 'current' : ''}" data-page="${n}">${n}</button>`)).join('')}
    <button class="btn btn-secondary" data-page="${page + 1}" ${page === pages ? 'disabled' : ''} aria-label="Next page">→</button>
  </nav>`;
}

