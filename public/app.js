async function runSmartSearch(text, btn) {
  text = text.trim();
  if (text.length < 3) return toast('Describe the home you want, for example "2 BHK in Baner under 90 lakh"');
  const original = btn.innerHTML;
  btn.disabled = true;
  btn.innerHTML = '<span class="spinner"></span> Finding matches…';
  try {
    const { summary, source, ...criteria } = await api('/ai/search', { method: 'POST', body: { query: text } });
    location.hash = `#/properties${qs({ match: JSON.stringify(criteria), ai: text, aiSummary: summary, aiSource: source })}`;
  } catch (err) {
    toast(err.message);
  } finally {
    btn.disabled = false;
    btn.innerHTML = original;
  }
}

