function formatINR(n) {
  if (prefs().priceFormat === 'full') return `₹${Math.round(n).toLocaleString('en-IN')}`;
  if (n >= 1e7) return `₹${trimNum(n / 1e7)} Cr`;
  if (n >= 1e5) return `₹${trimNum(n / 1e5)} L`;
  return `₹${Math.round(n).toLocaleString('en-IN')}`;
}

function shortINR(n) {
  if (n >= 1e7) return `₹${trimNum(n / 1e7, 1)}Cr`;
  if (n >= 1e5) return `₹${trimNum(n / 1e5, 0)}L`;
  return `₹${trimNum(n / 1e3, 0)}k`;
}

const priceLabel = (p) => (p.listingType === 'rent' ? `${formatINR(p.price)}<small> /month</small>` : formatINR(p.price));

function timeAgo(iso) {
  const days = Math.floor((Date.now() - new Date(iso)) / 86400000);
  if (days <= 0) return 'Today';
  if (days === 1) return 'Yesterday';
  if (days < 30) return `${days}d ago`;
  if (days < 365) return `${Math.floor(days / 30)}mo ago`;
  return `${Math.floor(days / 365)}y ago`;
}

const formatDate = (iso) => new Date(iso).toLocaleDateString('en-IN', { day: 'numeric', month: 'short', year: 'numeric' });

function stars(rating) {
  const full = Math.round(rating);
  return `<span class="stars" aria-label="${rating} out of 5">${'★'.repeat(full)}<span class="off">${'★'.repeat(5 - full)}</span></span>`;
}

function avatar(name, size = '') {
  let h = 0;
  for (const c of name) h = (h * 31 + c.charCodeAt(0)) % 360;
  const initials = name.split(' ').map((w) => w[0]).slice(0, 2).join('');
  return `<div class="avatar ${size}" style="background:hsl(${h} 32% 42%)" aria-hidden="true">${esc(initials)}</div>`;
}

async function api(path, options = {}) {
  const res = await fetch(`${window.API_BASE}/api${path}`, {
    headers: { 'Content-Type': 'application/json' },
    ...options,
    body: options.body ? JSON.stringify(options.body) : undefined,
  });
  const data = await res.json().catch(() => ({}));
  if (!res.ok) {
    const err = new Error(data.error || `Request failed (${res.status})`);
    err.status = res.status;
    err.errors = data.errors || {};
    throw err;
  }
  return data;
}

