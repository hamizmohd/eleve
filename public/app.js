const shortlist = {
  get() {
    try { return JSON.parse(localStorage.getItem('shortlist') || '[]'); } catch { return []; }
  },
  set(ids) {
    try { localStorage.setItem('shortlist', JSON.stringify(ids)); } catch { /* storage unavailable */ }
    updateShortlistBadge();
  },
  has(id) { return this.get().includes(id); },
  toggle(id) {
    const ids = this.get();
    const on = !ids.includes(id);
    this.set(on ? [...ids, id] : ids.filter((x) => x !== id));
    return on;
  },
};

