let currentRoute = null;
let currentView = null;

/** Applies display preferences (theme, text size, motion) to the document. */
function applyPrefs(s = prefs()) {
  const root = document.documentElement;
  const dark = s.theme === 'dark' || (s.theme === 'system' && Boolean(window.matchMedia?.('(prefers-color-scheme: dark)').matches));
  root.dataset.theme = dark ? 'dark' : 'light';
  root.dataset.text = s.textSize || 'medium';
  root.classList.toggle('reduce-motion', Boolean(s.reduceMotion));
}

function parseHash() {
  const raw = location.hash.replace(/^#\/?/, '');
  const [pathPart, queryPart = ''] = raw.split('?');
  const [route = '', ...params] = pathPart.split('/').filter(Boolean);
  return { route: route || 'home', params: params.map(decodeURIComponent), query: Object.fromEntries(new URLSearchParams(queryPart)) };
}

async function router() {
  const { route, params, query } = parseHash();
  const view = views[route] || views.home;
  const navKey = route === 'properties' ? query.listingType : route;
  document.querySelectorAll('[data-nav]').forEach((a) => a.classList.toggle('active', a.dataset.nav === navKey));
  sheet.close();

  try {
    if (route === currentRoute && view.update) {
      await view.update(query);
    } else {
      currentView?.destroy?.();
      currentView = view;
      currentRoute = route;
      if (route === 'home') document.title = 'Elevé · Buy & Rent Property in India';
      window.scrollTo({ top: 0 });
      await view.render(query, params);
    }
  } catch (err) {
    console.error(err);
    app.innerHTML = `<div class="container section">${emptyState('alert', 'Something went wrong', esc(err.message), '<button class="btn btn-primary" onclick="location.reload()">Retry</button>')}</div>`;
  }
}

async function init() {
  document.getElementById('menu-btn').addEventListener('click', () => openMenu());
  updateShortlistBadge();
  try {
    [META, ME] = await Promise.all([api('/meta'), api('/me')]);
  } catch {
    app.innerHTML = `<div class="container section">${emptyState('alert', 'Could not reach the server', 'Make sure the server is running (npm start) and reload.')}</div>`;
    return;
  }
  applyPrefs();
  window.matchMedia?.('(prefers-color-scheme: dark)').addEventListener?.('change', () => applyPrefs());
  updateMenuButton();
  document.getElementById('footer-cities').innerHTML = META.cities
    .map((c) => `<a href="#/properties${qs({ city: c.id })}">Homes in ${esc(c.name)}</a>`).join('');
  window.addEventListener('hashchange', router);
  router();
}

