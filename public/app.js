    this.query = query;
    const f = document.getElementById('agent-filters').elements;
    for (const name of ['city', 'specialization', 'language', 'minRating']) {
      f[name].value = query[name] || '';
      f[name].classList.toggle('set', Boolean(query[name]));
    }
    f.sort.value = query.sort || 'rating';
    document.getElementById('verified-toggle').classList.toggle('active', query.verified === 'true');
    if (document.activeElement !== f.q) f.q.value = query.q || '';
    const title = query.city ? `Agents in ${cityName(query.city)}` : 'Real estate agents';
    document.getElementById('agents-title').textContent = title;
    document.title = `${title} · Elevé`;

